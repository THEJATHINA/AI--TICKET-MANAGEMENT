def clean_text(text: str) -> str:
    """
    Cleans raw text by:
    1. Converting to lowercase.
    2. Removing special characters and punctuation.
    3. Removing extra whitespaces.
    4. Removing standard stopwords.
    """
    if not text:
        return ""
    
    # Convert to lowercase
    text = text.lower()
    
    # Remove HTML tags (if any)
    text = re.sub(r'<[^>]*>', ' ', text)
    
    # Keep only alphabetic characters and numbers
    text = re.sub(r'[^a-zA-Z0-9\s]', ' ', text)
    
    # Tokenize and remove stop words
    words = text.split()
    cleaned_words = [w for w in words if w not in STOPWORDS]
    
    # Reconstruct the string
    return " ".join(cleaned_words)

def prepare_input(subject: str, description: str) -> str:
    """
    Combines and cleans subject and description for the model input.
    """
    combined = f"{subject or ''} {description or ''}"
    return clean_text(combined)
